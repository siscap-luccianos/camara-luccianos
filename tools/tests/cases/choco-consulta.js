const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const page = await (await b.newContext({ viewport: { width: 390, height: 900 } })).newPage();
  const err=[]; page.on("pageerror",e=>err.push(e.message)); page.on("console",m=>{if(m.type()==="error"&&!/ERR_|404/.test(m.text())) err.push(m.text())});
  const ok=(c,m)=>console.log((c?"OK   ":"FALLA")+" "+m);
  await page.goto("http://localhost:8998/"); await page.waitForSelector("#authLocal");
  await page.fill("#authLocal","Operaciones"); await page.click("#authLocalOk");
  await page.fill("#authClave","op2024"); await page.click("#authClaveOk");
  await page.waitForSelector("[data-authemp]"); await page.click("[data-authemp]"); if(await page.waitForSelector("[data-tecla]",{timeout:900}).catch(()=>null)){ for(const d of "1234") await page.click('[data-tecla="'+d+'"]') }
  await page.waitForSelector("header"); await page.waitForTimeout(300);
  await page.fill("#local","Local prueba"); await page.press("#local","Enter"); await page.waitForTimeout(1000);
  await page.click("#tabs [data-t='salida']"); await page.waitForTimeout(300);
  const tabs=await page.$$eval(".tabCat",e=>e.map(x=>x.dataset.familia)); ok(tabs.includes("chocolateria"),"la pestaña Chocolatería aparece en Salida: "+tabs.join(","));
  await page.click(".tabCat[data-familia='chocolateria']"); await page.waitForTimeout(300);
  ok(!!(await page.$(".consultaAviso")),"cartel «Solo informativo»");
  ok((await page.$$(".card.consulta")).length===2,"2 tarjetas de consulta");
  ok((await page.$$("[data-add]")).length===0,"ninguna tarjeta suma (sin data-add)");
  const txt=(await page.$eval("main",e=>e.textContent)).replace(/\s+/g," ");
  ok(/Alfajor Semiamargo/.test(txt)&&/vencen en \d+ días/.test(txt),"muestra una línea por lote («N vencen en X días»)");
  ok(/Sin fecha todavía/.test(txt)||/sin fecha/i.test(txt),"muestra lo sin fecha");
  const cls=await page.$$eval(".card.consulta>.pick",e=>e.map(x=>x.className)); console.log(cls.join(" | "));
  ok(cls.some(c=>/sem-rojo/.test(c)),"semáforo rojo en el que vence en 3 días");
  await page.click(".card.consulta"); await page.waitForTimeout(150);
  ok(/Solo consulta/.test(await page.$eval("#toast",e=>e.textContent)),"tocar una tarjeta avisa que es solo consulta");
  await page.screenshot({path:"choco-consulta.png"});
  await page.click("#irVentaDia2"); await page.waitForTimeout(300);
  ok(/Venta del día/.test(await page.$eval("main",e=>e.textContent)),"el botón del cartel lleva a Salida de chocolatería");
  await page.reload(); await page.waitForSelector("header"); await page.waitForTimeout(800);
  await page.evaluate(()=>{ S.empleado.rol="colaborador"; S.modoVenta=false; S.tab="salida"; S.filtroFamilia="chocolateria"; renderApp() });
  await page.waitForTimeout(200);
  ok(!(await page.$("#irVentaDia2"))&&/La carga un responsable/.test(await page.$eval("main",e=>e.textContent)),"colaborador: sin botón, con aviso «La carga un responsable»");
  console.log("errores:",JSON.stringify(err)); await b.close();
})();
