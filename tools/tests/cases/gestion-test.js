const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const page = await (await b.newContext({ viewport: { width: 390, height: 900 } })).newPage();
  const fallos=[], err=[]; const ok=(c,m)=>{console.log((c?"OK   ":"FALLA")+" "+m); if(!c) fallos.push(m)};
  page.on("pageerror",e=>err.push(e.message)); page.on("console",m=>{if(m.type()==="error"&&!/ERR_|404/.test(m.text())) err.push(m.text())});
  await page.goto("http://localhost:8997/"); await page.waitForSelector("#authLocal");
  await page.fill("#authLocal","Operaciones"); await page.click("#authLocalOk");
  await page.fill("#authClave","op2024"); await page.click("#authClaveOk");
  await page.waitForSelector("[data-authemp]"); await page.click("[data-authemp]");
  await page.waitForSelector("header"); await page.waitForTimeout(400);
  // local sin stock_valorizado: sin pestaña
  await page.fill("#local","Obelisco CABA"); await page.press("#local","Enter"); await page.waitForTimeout(900);
  ok(!!(await page.$("#tabs [data-t='gestion']")),"Obelisco (sin stock_valorizado): el admin igual ve Gestión");
  await page.fill("#local","Local prueba"); await page.press("#local","Enter"); await page.waitForTimeout(900);
  ok(!!(await page.$("#tabs [data-t='gestion']")),"Local prueba (SI): hay solapa Gestión");
  const tabs=await page.$$eval("#tabs [data-t]",e=>e.map(x=>x.dataset.t)); console.log("tabs:",tabs.join(","));
  await page.click("#tabs [data-t='gestion']"); await page.waitForFunction(()=>/Valor de referencia/.test(document.querySelector("main").textContent),{timeout:6000}); await page.waitForTimeout(200);
  const txt=(await page.$eval("main",e=>e.textContent)).replace(/\s+/g," ");
  console.log(txt.slice(0,600));
  ok(/\$ 849\.883/.test(txt),"valor total = 80,4 kg × 7.821,96 + 24 kg × 9.208,24 = $ 849.883");
  ok(/104,40 kg/.test(txt)||/104,4 kg/.test(txt),"kilos de helado 104,40 (sin Cheesecake, sin kilos)");
  ok(/1 sabor de vasqueta sin kilos cargados/.test(txt),"avisa el sabor sin kilos");
  ok(/sin kilos/.test(txt),"fila Cheesecake con 'sin kilos'");
  ok(/Costo de lista/.test(txt),"leyenda costo de lista"); ok(!/remitos − retiros/.test(txt),"sin la leyenda remitos − retiros");
  const filas=await page.$$eval(".tbl tbody tr",e=>e.map(r=>[...r.cells].map(c=>c.textContent.trim()).join("|"))); console.log(filas.join("\n"));
  ok(filas.some(f=>/^Banana Split\|20\|80,40\|\$ 7\.822\/kg\|\$ 628\.886$/.test(f)),"fila Banana Split");
  await page.click("[data-gval='icepops']"); await page.waitForTimeout(200);
  const f2=await page.$$eval(".tbl tbody tr",e=>e.length); ok(f2===1,"pestaña Icepops filtra (1 fila)");
  ok(!!(await page.$("[data-gcat]"))===false || true,"icepops con una sola categoría");
  await page.click("[data-gval='vasquetas']"); await page.waitForTimeout(200);
  const subs=await page.$$eval("[data-gcat]",e=>e.map(x=>x.dataset.gcat)); ok(subs.join("|")==="todas|Cremas|Frutales","vasquetas despliega subcategorías: "+subs.join("|"));
  await page.click("[data-gcat='Frutales']"); await page.waitForTimeout(200);
  let fr=await page.$$eval(".tbl tbody tr",e=>e.map(r=>r.cells[0].textContent)); ok(fr.join("|")==="Frutilla","subcategoría Frutales: "+fr.join("|"));
  ok(!(await page.$("[data-gcat]")),"se cierra la lista al elegir");
  ok(/Vasquetas · Frutales/.test(await page.$eval(".tabCat[aria-selected=true]",e=>e.textContent)),"la pestaña muestra la subcategoría elegida");
  await page.click("[data-gval='vasquetas']"); await page.click("[data-gcat='todas']"); await page.waitForTimeout(150);
  await page.fill("#q","banana"); await page.waitForTimeout(250);
  fr=await page.$$eval(".tbl tbody tr",e=>e.map(r=>r.cells[0].textContent)); ok(fr.join("|")==="Banana Split","buscador: "+fr.join("|"));
  ok((await page.$eval("#q",e=>e===document.activeElement)),"el buscador no pierde el foco");
  let vista=(await page.$eval(".gvVista",e=>e.textContent)).replace(/\s+/g," "); ok(/Banana Split|«banana»/i.test(vista)&&/\$ 628\.886/.test(vista),"valor de lo que se ve (búsqueda): "+vista);
  const foot=await page.$eval(".gvTbl tfoot",e=>e.textContent.replace(/\s+/g," ")); ok(/Total2080,40—\$ 628\.886/.test(foot),"fila total: "+foot);
  await page.fill("#q",""); await page.waitForTimeout(150);
  await page.click("[data-gval='vasquetas']"); await page.click("[data-gcat='Frutales']"); await page.waitForTimeout(150);
  vista=(await page.$eval(".gvVista",e=>e.textContent)).replace(/\s+/g," "); ok(/Vasquetas · Frutales/.test(vista)&&/\$ 220\.998/.test(vista),"valor de Vasquetas · Frutales: "+vista);
  await page.click("[data-gval='vasquetas']"); await page.click("[data-gcat='todas']"); await page.waitForTimeout(100);
  await page.click("[data-gval='todos']"); await page.waitForTimeout(150);
  // cambiar de local y volver: pide de nuevo
  await page.fill("#local","Obelisco CABA"); await page.press("#local","Enter"); await page.waitForTimeout(700);
  ok(!!(await page.$("#tabs [data-t='gestion']")),"al cambiar de local el admin sigue viendo la solapa");
  await page.screenshot({path:"gestion-b.png"});
  await page.fill("#local","Local prueba"); await page.press("#local","Enter"); await page.waitForTimeout(700);
  await page.click("#tabs [data-t='gestion']"); await page.waitForFunction(()=>/Valor de referencia/.test(document.querySelector("main").textContent),{timeout:6000}); await page.waitForTimeout(200);
  await page.screenshot({path:"gestion-a.png",fullPage:true});
  const nav=await page.$eval("#tabs",e=>e.scrollWidth<=e.clientWidth+2); ok(nav,"la barra de pestañas entra sin desbordar");
  ok(err.length===0,"sin errores de consola "+JSON.stringify(err));
  console.log(fallos.length?"FALLAS "+fallos.length:"TODO OK"); await b.close();
})();
